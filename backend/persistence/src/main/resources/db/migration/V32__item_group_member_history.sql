-- YPJ-54: item_group_member 加/离留痕(episode 式,spec 0041);同表服务 sprint 与 release 两类分组。
create table item_group_member_history (
    id          bigint generated by default as identity primary key,
    object_id   uuid          not null,
    group_id    bigint        not null,
    item_id     bigint        not null,
    added_at    timestamptz   not null,
    removed_at  timestamptz,

    constraint uk_igmh_object_id unique (object_id),
    -- 级联:sprint/release 删除(须空,判空只查 item_group_member)时历史行连带清理,409 语义不回归(YPJ-54);
    -- item 仅软删,cascade 不触发,留痕随 item 存续。
    constraint fk_igmh_group     foreign key (group_id) references item_group (id) on delete cascade,
    constraint fk_igmh_item      foreign key (item_id) references item (id) on delete cascade
);

-- 应用层不变量落库:同组同 item 至多一个在册 episode(sprint/release 均为替换式归属)。
create unique index ux_igmh_open on item_group_member_history (group_id, item_id) where removed_at is null;

create index ix_igmh_item on item_group_member_history(item_id);

-- 存量回填:仅 added_at 可回填(= created_at);removed 不可回填(口径:上线时点起 removed 精确,spec 0037 §四)。
insert into item_group_member_history (object_id, group_id, item_id, added_at)
select gen_random_uuid(), group_id, item_id, created_at from item_group_member;
