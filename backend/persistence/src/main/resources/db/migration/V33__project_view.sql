-- YPJ-47: 表格视图配置(筛选+列配置,按 用户×项目 私有保存,spec 0045)
-- filters/columns 为小 JSON 串,用 TEXT(Spring Data JDBC 无 JSONB 映射先例,避免 PGobject 转换器)
create table project_view (
    id          bigint generated by default as identity primary key,
    object_id   uuid         not null,
    project_id  bigint       not null,
    creator_id  bigint       not null,
    name        varchar(100) not null,
    filters     text         not null default '{}',
    columns     text         not null default '{}',
    created_at  timestamptz  not null default now(),
    updated_at  timestamptz  not null default now(),
    constraint uk_pv_object_id unique (object_id),
    constraint fk_pv_project foreign key (project_id) references project (id),
    constraint fk_pv_creator foreign key (creator_id) references member (id)
);
create index ix_pv_project_creator on project_view (project_id, creator_id);
-- 同一用户同项目视图名唯一
create unique index ux_pv_name on project_view (project_id, creator_id, name);
