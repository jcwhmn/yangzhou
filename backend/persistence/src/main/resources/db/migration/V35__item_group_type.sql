-- YPJ-48: V73 ItemGroupType 运行时定义(spec docs/spec/0056-v73-item-group-type.md;PRD §6)
-- item_group_type:项目级 group 类型运行时定义;builtin 种子 sprint/release,自定义类型走最小语义
-- item_group.type 保持 varchar,放开 CHECK,service 层校验必须命中项目类型行

create table item_group_type (
    id          bigint generated by default as identity primary key,
    object_id   uuid        not null,
    project_id  bigint      not null,
    type_key    varchar(20) not null,
    name        varchar(50) not null,
    builtin     boolean     not null default false,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now(),
    created_by  bigint,
    updated_by  bigint,

    constraint uk_item_group_type_object_id unique (object_id),
    constraint uk_item_group_type           unique (project_id, type_key),
    constraint fk_item_group_type_project   foreign key (project_id) references project (id)
);

create index ix_item_group_type_project on item_group_type(project_id);

-- 既有项目种子:sprint 全种;release 仅对用过 release 的项目(新建项目由 ProjectService 双种)
insert into item_group_type (object_id, project_id, type_key, name, builtin)
select gen_random_uuid(), id, 'sprint', 'Sprint', true from project;

insert into item_group_type (object_id, project_id, type_key, name, builtin)
select gen_random_uuid(), p.id, 'release', 'Release', true
from project p
where exists (select 1 from item_group g where g.project_id = p.id and g.type = 'release');

alter table item_group drop constraint ck_item_group_type;
