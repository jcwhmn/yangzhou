-- YPJ-50:V23 附件存储(spec docs/spec/0063-v50-attachment-s3.md)
-- 附件元数据;字节在 S3 兼容存储(presign 直传直取),object_key 即桶内路径。
-- item 硬删走 FK cascade(回收站软删不动附件行);审计四元组照 V34 约定(bigint 无 FK)。

create table attachment (
    id          bigint generated by default as identity primary key,
    object_id   uuid          not null,
    item_id     bigint        not null,
    filename    varchar(255)  not null,
    content_type varchar(100) not null,
    size_bytes  bigint        not null,
    object_key  varchar(500)  not null,
    created_at  timestamptz   not null default now(),
    updated_at  timestamptz   not null default now(),
    created_by  bigint,
    updated_by  bigint,

    constraint uk_attachment_object_id unique (object_id),
    constraint uk_attachment_object_key unique (object_key),
    constraint fk_attachment_item      foreign key (item_id) references item (id) on delete cascade,
    constraint ck_attachment_size      check (size_bytes >= 0)
);

create index ix_attachment_item on attachment(item_id);
