-- YPJ-139(spec 0097 S2):GroupWorkflow 挂 ItemGroupType——类型级状态机,组实例只存 currentStatus(item_group.status varchar)。
-- group_status_transition 不建表(用户裁决:出边依附 status)——出边内嵌 group_status.transitions JSON,结构与 item 侧一致。
-- 组状态变更走动作白名单(spec 3.2 动作端点);存量组 status 值不动(种子状态名与现值兼容:planned/active/completed/released)。

create table group_status (
    id            bigint generated by default as identity primary key,
    object_id     uuid        not null,
    group_type_id bigint      not null,
    name          varchar(50) not null,
    status_type   varchar(20) not null,
    transitions   text        not null default '[]',
    position      int         not null default 0,
    created_at    timestamptz not null default now(),
    updated_at    timestamptz not null default now(),
    constraint uk_group_status_object_id unique (object_id),
    constraint uk_group_status_type_name unique (group_type_id, name),
    constraint fk_group_status_type foreign key (group_type_id) references item_group_type (id) on delete cascade,
    constraint ck_group_status_status_type check (status_type in ('START', 'FINAL', 'ACTIVE'))
);

-- 种子:对每个 item_group_type 按 type_key 种状态机(sprint/release 内建;其余按自定义默认三态全连通 switch,与现状「任意改」一致零破坏)
insert into group_status (object_id, group_type_id, name, status_type, transitions, position)
select gen_random_uuid(), t.id, s.name, s.stype, s.edges::text, s.pos
from item_group_type t
cross join (values
    ('planned',   'START',  '[{"function":"start","target":"active"}]', 0),
    ('active',    'ACTIVE', '[{"function":"complete","target":"completed"},{"function":"backward","target":"planned"}]', 1),
    ('completed', 'FINAL',  '[]', 2)
) as s(name, stype, edges, pos)
where t.type_key = 'sprint'

union all

select gen_random_uuid(), t.id, s.name, s.stype, s.edges::text, s.pos
from item_group_type t
cross join (values
    ('planned',  'START',  '[{"function":"complete","target":"released"}]', 0),
    ('released', 'FINAL',  '[]', 1)
) as s(name, stype, edges, pos)
where t.type_key = 'release'

union all

select gen_random_uuid(), t.id, s.name, s.stype, s.edges::text, s.pos
from item_group_type t
cross join (values
    ('planned',   'START',  '[{"function":"switch","target":"active"}]', 0),
    ('active',    'ACTIVE', '[{"function":"switch","target":"completed"}]', 1),
    ('completed', 'FINAL',  '[{"function":"switch","target":"planned"}]', 2)
) as s(name, stype, edges, pos)
where t.type_key <> 'sprint' and t.type_key <> 'release';
