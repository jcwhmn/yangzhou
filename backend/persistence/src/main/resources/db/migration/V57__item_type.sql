-- YPJ-177(spec 0123):item_type 项目级运行时定义——镜像 item_group_type(V35,object_id 形态随 V41)
-- item.type 保持 varchar,放开 CHECK,service 层校验必须命中项目类型行
-- 值语义(spec 0123 ①,2026-11-14 定):story=主线单元/task=插入小活/bug=缺陷/goal=树根容器

create table item_type (
    id          bigint generated by default as identity primary key,
    object_id   uuid        not null,
    project_object_id uuid  not null,
    type_key    varchar(20) not null,
    name        varchar(50) not null,
    builtin     boolean     not null default false,
    created_at  timestamptz not null default now(),
    updated_at  timestamptz not null default now(),
    created_by_object_id uuid,
    updated_by_object_id uuid,

    constraint uk_item_type_object_id unique (object_id),
    constraint uk_item_type           unique (project_object_id, type_key),
    constraint fk_item_type_project   foreign key (project_object_id) references project (object_id),
    constraint fk_item_type_created_by foreign key (created_by_object_id) references member (object_id),
    constraint fk_item_type_updated_by foreign key (updated_by_object_id) references member (object_id)
);

create index ix_item_type_project on item_type(project_object_id);

