-- YPJ-184(spec 0125):item commits 快照——数据自持(离分支离 GitHub 均可得);
-- 双写路径:Done 联动(captured_by=finalize,终止时间锚)+ 读时缓存(captured_by=read);
-- upsert 幂等按 (item, repo, ref),以最后一次抓取为准(重开再 Done 刷新 captured_at)。
-- commits_json 用 text 存 JSON 数组:消费方永远整 ref 时间轴读取(无 SQL 级 commit 查询),
-- Spring Data JDBC 仓内无 jsonb 实体先例,引入 Converter 属投机基建;将来要 commit 级
-- 查询再迁 jsonb(text→jsonb 迁移零损,jsonb 消化 text 合法)。
-- via/captured_by 为系统枚举,按仓纪律 VARCHAR + CHECK。

create table item_commit_snapshot (
    id             bigint generated by default as identity primary key,
    object_id      uuid        not null,
    item_object_id uuid        not null,
    repo           text        not null,
    ref            text        not null,
    via            varchar(16) not null default 'branch',
    commits_json   text        not null,
    commit_count   int         not null,
    captured_at    timestamptz not null,
    captured_by    varchar(16) not null default 'read',
    created_at     timestamptz not null default now(),
    updated_at     timestamptz,

    constraint uk_item_commit_snapshot_object_id unique (object_id),
    constraint uk_item_commit_snapshot_ref unique (item_object_id, repo, ref),
    constraint fk_item_commit_snapshot_item foreign key (item_object_id) references item (object_id),
    constraint ck_item_commit_snapshot_via check (via in ('branch', 'pr')),
    constraint ck_item_commit_snapshot_captured_by check (captured_by in ('read', 'finalize')),
    constraint ck_item_commit_snapshot_count check (commit_count > 0)
);

create index ix_item_commit_snapshot_item on item_commit_snapshot(item_object_id);
