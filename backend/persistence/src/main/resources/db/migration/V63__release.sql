-- YPJ-191(spec 0132):US-R1 Release 独立实体(PRD v1.2 §4.1/§5.1)
-- Release = 交付事件(非 ItemGroup,YPJ-165 拆除后重建);planned→released 单向终态
-- stage 封闭枚举(alpha/beta/rc/ga,显示词外置文案层);version 归组维度(非实体);序号不建模靠 name
-- 形态对齐 V41 后 milestone:project_object_id FK + 审计 FK 列
create table release (
    id          bigint generated by default as identity primary key,
    object_id   uuid          not null,
    project_object_id uuid   not null,
    name        varchar(100)  not null,
    version     varchar(50),
    stage       varchar(10),
    status      varchar(20)   not null default 'planned',
    target_date date,
    released_date date,
    created_at  timestamptz   not null default now(),
    updated_at  timestamptz   not null default now(),
    created_by_object_id uuid,
    updated_by_object_id uuid,

    constraint uk_release_object_id unique (object_id),
    constraint fk_release_project  foreign key (project_object_id) references project (object_id),
    constraint ck_release_stage    check (stage in ('alpha', 'beta', 'rc', 'ga')),
    constraint ck_release_status   check (status in ('planned', 'released'))
);

create index ix_release_project on release(project_object_id);
