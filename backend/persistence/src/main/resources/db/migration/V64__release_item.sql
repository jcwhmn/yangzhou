-- YPJ-200(spec 0133):US-R3 item 挂接——release_item 叉表
-- 镜像 milestone_item(V55):弱引用无 FK(挂接清理走代码路径),uk 挡重
create table release_item (
    id          bigint generated by default as identity primary key,
    object_id   uuid not null,
    release_object_id uuid not null,
    item_object_id    uuid not null,
    created_at  timestamptz not null default now(),
    constraint uk_release_item_object_id unique (object_id),
    constraint uk_release_item           unique (release_object_id, item_object_id)
);
