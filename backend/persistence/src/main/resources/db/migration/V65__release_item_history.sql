-- YPJ-202(spec 0135):US-R6 挂接变更留痕——release_item_history
-- 弱引用无 FK(同 release_item);history 行永不删(release 删除也不清,审计靠它)
create table release_item_history (
    id                bigint generated by default as identity primary key,
    object_id         uuid not null,
    release_object_id uuid not null,
    item_object_id    uuid not null,
    action            varchar(20) not null check (action in ('attached', 'detached')),
    actor_member_object_id uuid,
    created_at        timestamptz not null default now(),
    constraint uk_release_item_history_object_id unique (object_id)
);
